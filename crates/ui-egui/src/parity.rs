//! Menu parity against Guitar Pro 8: which [`crate::menu_catalog`] items are live.
//! `cargo xtask parity` writes the report to `docs/parity-checklist.md`.
//!
//! When parity rises, raise [`FLOOR`] to the new live count (never lower it).

use crate::menu_catalog::{Action, CATALOG, MenuItem, TOP};
use guitario_engine::registry;

/// Live menu items on `main`. A test fails if parity drops below this.
pub const FLOOR: usize = 119;

pub fn is_live(item: &MenuItem) -> bool {
    match item.action {
        Action::Cmd(id, params) => registry().iter().any(|c| c.id == id) && (params.is_empty() || serde_json::from_str::<serde_json::Value>(params).is_ok()),
        Action::Ui(_) => true,
        Action::Missing => false,
    }
}

pub fn live_count() -> (usize, usize) {
    crate::menu_catalog::counts(is_live)
}

fn pct(a: usize, b: usize) -> String {
    if b == 0 { "0%".into() } else { format!("{:.0}%", a as f64 * 100.0 / b as f64) }
}

/// The Markdown report, deterministic for `--check`.
pub fn report() -> String {
    let (live, total) = live_count();
    let mut s = String::new();
    s.push_str("# Guitar Pro menu parity checklist\n\n");
    s.push_str("Generated by `cargo xtask parity` from `crates/ui-egui/src/menu_catalog.rs`. Do not edit by hand.\n\n");
    s.push_str("The catalog lists Guitar Pro 8's menu items from its documentation and observation; it was not measured from the installed app (see [target-app-parity](target-app-parity.md#target-measured)). A live item runs an engine command or shell action; this says nothing about how deep the behaviour behind it goes.\n\n");
    s.push_str(&format!("**Live:** {live} of {total} menu items ({})\n\n", pct(live, total)));
    s.push_str("| Menu | Live | Total | % |\n|---|---:|---:|---:|\n");
    for top in TOP {
        let items: Vec<&MenuItem> = CATALOG.iter().filter(|i| i.path.split('/').next() == Some(top)).collect();
        let l = items.iter().filter(|i| is_live(i)).count();
        s.push_str(&format!("| {top} | {l} | {} | {} |\n", items.len(), pct(l, items.len())));
    }
    for top in TOP {
        s.push_str(&format!("\n## {top}\n\n| Item | Status | Runs |\n|---|---|---|\n"));
        for i in CATALOG.iter().filter(|i| i.path.split('/').next() == Some(top)) {
            let name = match i.path.split_once('/') {
                Some((_, sub)) => format!("{} › {}", sub.replace('/', " › "), i.label),
                None => i.label.to_string(),
            };
            let (status, runs) = match i.action {
                Action::Cmd(id, "") => ("live", format!("`{id}`")),
                Action::Cmd(id, p) => ("live", format!("`{id}` `{p}`")),
                Action::Ui(a) => ("live", format!("shell: {a:?}")),
                Action::Missing => ("**missing**", String::new()),
            };
            let status = if matches!(i.action, Action::Cmd(..)) && !is_live(i) { "**broken**" } else { status };
            s.push_str(&format!("| {name} | {status} | {runs} |\n"));
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_command_item_names_a_real_command() {
        for i in CATALOG {
            if let Action::Cmd(id, _) = i.action {
                assert!(is_live(i), "menu item {}/{} runs unknown command `{id}` or bad params", i.path, i.label);
            }
        }
    }

    #[test]
    fn parity_never_drops() {
        let (live, total) = live_count();
        assert!(live >= FLOOR, "menu parity fell to {live}/{total}, below the floor {FLOOR}");
    }

    #[test]
    fn items_are_unique_and_under_known_menus() {
        let mut seen = std::collections::BTreeSet::new();
        for i in CATALOG {
            assert!(TOP.contains(&i.path.split('/').next().unwrap_or("")), "{} is not under a top menu", i.path);
            assert!(seen.insert((i.path, i.label)), "duplicate {}/{}", i.path, i.label);
        }
    }

    #[test]
    fn catalog_shortcuts_parse() {
        for i in CATALOG.iter().filter(|i| !i.shortcut.is_empty()) {
            assert!(crate::keys::parse(i.shortcut).is_some(), "{}: bad shortcut {}", i.label, i.shortcut);
        }
    }
}
